"""Реализация на своих данных: партнёр, контрагент и договор создаются кодом, выбираются в форме; всё удаляется."""
import uuid

from scenario import ORGANIZATION, new_sale

CREATE = '''
Партнер = Справочники._ДемоПартнеры.СоздатьЭлемент();
Партнер.Наименование = Параметры["Имя"];
Партнер.Клиент = Истина;
Партнер.Записать();
Контрагент = Справочники._ДемоКонтрагенты.СоздатьЭлемент();
Контрагент.Наименование = Параметры["Имя"];
Контрагент.Партнер = Партнер.Ссылка;
Контрагент.Записать();
Договор = Справочники._ДемоДоговорыКонтрагентов.СоздатьЭлемент();
Договор.Наименование = Параметры["Имя"];
Договор.Владелец = Контрагент.Ссылка;
Договор.Партнер = Партнер.Ссылка;
Договор.Организация = Справочники._ДемоОрганизации.НайтиПоНаименованию(Параметры["Организация"], Истина);
Договор.ВалютаРасчетов = Справочники.Валюты.НайтиПоКоду("643");
Договор.Записать();
Результат = Новый Структура("Партнер,Контрагент,Договор", Партнер.Ссылка, Контрагент.Ссылка, Договор.Ссылка);
'''


def test_sale_on_own_partner(testpilot, testpilot_data):
    name = f'TP Протон {uuid.uuid4().hex[:8]}'
    testpilot_data.create(CREATE, {'Имя': name, 'Организация': ORGANIZATION})
    form = new_sale(testpilot, partner=name, contract=name)
    form.find_object(name='ФормаПровести').click()
    testpilot_data.track_window()
