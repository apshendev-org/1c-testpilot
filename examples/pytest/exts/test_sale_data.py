"""Реализация на своих данных: партнёр и контрагент создаются кодом, выбираются в форме; всё удаляется."""
import uuid

from scenario import new_sale

CREATE = '''
Партнер = Справочники._ДемоПартнеры.СоздатьЭлемент();
Партнер.Наименование = Параметры["Имя"];
Партнер.Клиент = Истина;
Партнер.Записать();
Контрагент = Справочники._ДемоКонтрагенты.СоздатьЭлемент();
Контрагент.Наименование = Параметры["Имя"];
Контрагент.Партнер = Партнер.Ссылка;
Контрагент.Записать();
Результат = Новый Структура("Партнер,Контрагент", Партнер.Ссылка, Контрагент.Ссылка);
'''


def test_sale_on_own_partner(testpilot, testpilot_data):
    name = f'TP Протон {uuid.uuid4().hex[:8]}'
    testpilot_data.create(CREATE, {'Имя': name})
    form = new_sale(testpilot, partner=name)
    form.find_object(name='ФормаПровести').click()
    testpilot_data.track_window()
